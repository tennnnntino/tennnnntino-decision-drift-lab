"""Regenerate docs/walkthrough-case.mjs from the packaged synthetic corpus.

The browser cannot read the corpus JSON (connect-src 'none'), so the single case
used by the walkthrough is shipped as a module snapshot. tests/test_v14_parity.py
fails when the snapshot and the corpus diverge.

    python tools/build_walkthrough_case.py          # rewrite the snapshot
    python tools/build_walkthrough_case.py --check  # exit 1 if it is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ddlab.corpus import find_case  # noqa: E402

CASE_ID = "HD-25"
TARGET = ROOT / "docs" / "walkthrough-case.mjs"


def render() -> str:
    split, case = find_case(CASE_ID)
    return ("/* GENERATED by tools/build_walkthrough_case.py from research/handoff-corpus-v1_4. Do not edit.\n"
            "   Fictional conversation. Labels are model-drafted candidates, not human-reviewed truth. */\n"
            f"export const WALKTHROUGH_SPLIT = {json.dumps(split)};\n"
            f"export const WALKTHROUGH_CASE = {json.dumps(case, ensure_ascii=False, indent=1)};\n")


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print("STALE: docs/walkthrough-case.mjs does not match the corpus", file=sys.stderr)
            return 1
        print("OK: snapshot matches the corpus")
        return 0
    TARGET.write_bytes(text.encode("utf-8"))
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
