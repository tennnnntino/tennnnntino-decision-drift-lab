"""Regenerate docs/policy.mjs from contracts/authorization-policy.json and its schema.

The browser cannot read JSON files (connect-src 'none'), so the packaged default
policy and its schema are shipped as a module snapshot. A test fails when the
snapshot and the contract files diverge.

    python tools/build_policy_module.py          # rewrite the snapshot
    python tools/build_policy_module.py --check  # exit 1 if it is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ddlab.policy import DEFAULT_POLICY_PATH, POLICY_SCHEMA_PATH, load_policy  # noqa: E402

TARGET = ROOT / "docs" / "policy.mjs"


def render() -> str:
    policy = load_policy(DEFAULT_POLICY_PATH)
    schema = json.loads(POLICY_SCHEMA_PATH.read_text(encoding="utf-8"))
    for annotation in ("$schema", "$id"):  # identifiers only; the page carries no URL
        schema.pop(annotation, None)
    return ("/* GENERATED by tools/build_policy_module.py from contracts/authorization-policy*.json. Do not edit.\n"
            "   Operator-side simulation policy: which declared actions need a simulated human approval.\n"
            "   It is never read from an analysed case and it authenticates nobody. */\n"
            f"export const DEFAULT_POLICY = {json.dumps(policy, ensure_ascii=False, indent=1)};\n"
            f"export const POLICY_SCHEMA = {json.dumps(schema, ensure_ascii=False, indent=1)};\n"
            "export const POLICY_LIKE_KEYS = ['authorization_policy', 'exempt', 'exempt_actions', 'policy', 'policy_id'];\n")


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print("STALE: docs/policy.mjs does not match the policy contract", file=sys.stderr)
            return 1
        print("OK: policy snapshot matches the contract")
        return 0
    TARGET.write_bytes(text.encode("utf-8"))
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
